MONO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
MONOB = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
SANSB = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

def f(size, bold=False, mono=False):
    if mono:
        return ImageFont.truetype(MONOB if bold else MONO, size)
    return ImageFont.truetype(SANSB if bold else SANS, size)

def base():
    img = Image.new("RGB", (W, H), BG)
    return img, ImageDraw.Draw(img)

def wrap(draw, text, font, maxw):
    words, lines, cur = text.split(), [], ""
    for w_ in words:
        t = (cur + " " + w_).strip()
        if draw.textlength(t, font=font) <= maxw:
            cur = t
        else:
            lines.append(cur); cur = w_
    if cur:
        lines.append(cur)
    return lines

def text_card(name, kicker, lines, accent=GREEN, big=64):
    """Centered text card. lines = list of (text, size, color) or plain str."""
    img, d = base()
    y = 200
    if kicker:
        d.text((W//2, y), kicker, font=f(28), fill=DIM, anchor="mm")
        y += 70
    for item in lines:
        if isinstance(item, str):
            item = (item, big, TXT)
        text, size, color = item
        font = f(size, bold=True)
        for ln in wrap(d, text, font, W - 320):
            d.text((W//2, y), ln, font=font, fill=color, anchor="ma")
            y += int(size * 1.35)
        y += 18
    img.save(f"{OUT}/{name}.png")
    return name

def term_window(d, title="zack@vm: ~/workspace/wreck"):
    d.rectangle([60, 40, W-60, H-60], fill=PANEL, outline=BORDER, width=2)
    d.rectangle([60, 40, W-60, 96], fill=(26, 26, 36), outline=BORDER, width=2)
    d.ellipse([84, 58, 100, 74], fill=RED)
    d.ellipse([108, 58, 124, 74], fill=AMBER)
    d.ellipse([132, 58, 148, 74], fill=GREEN)
    d.text((W//2, 68), title, font=f(24, mono=True), fill=DIM, anchor="mm")

def color_for(line):
    s = line.strip()
    if "ACCEPT" in s or "Merged" in s or "HOLDS" in s or "sealed: 5" in s:
        return GREEN
    if "REJECT" in s:
        return RED
    if s.startswith("+") or s.startswith("="):
        return DIM
    return TXT

def term_still(name, prompt_cmd, body_lines, font_size=27, scroll=0, extra_note=None):
    img, d = base()
    term_window(d)
    y0, line_h = 130, int(font_size * 1.42)
    max_lines = (H - 120 - y0) // line_h
    x = 110
    font, bfont = f(font_size, mono=True), f(font_size, bold=True, mono=True)
    d.text((x, y0), "$ ", font=bfont, fill=GREEN)
    d.text((x + d.textlength("$ ", font=bfont), y0), prompt_cmd, font=font, fill=TXT)
    y = y0 + line_h
    for ln in body_lines[scroll:scroll + max_lines - 1]:
        col = color_for(ln)
        use = bfont if ("ACCEPT" in ln or "REJECT" in ln or "human merge" in ln or "decisions/sec" in ln or "HOLDS" in ln) else font
        shown = ln if len(ln) <= 100 else ln[:97] + "..."
        d.text((x, y), shown, font=use, fill=col)
        y += line_h
    if extra_note:
        d.text((W//2, H-100), extra_note, font=f(24), fill=DIM, anchor="mm")
    img.save(f"{OUT}/{name}.png")
    return name


    img, d = base()
    term_window(d, title="dashboard.html — wreck change field (faithful render of the real generated file)")
    cards = [("5", "agents", TXT), ("5", "changes", TXT), ("3", "accepted", GREEN),
             ("2", "rejected", RED), ("0", "human merges", GREEN), ("5", "sealed", AMBER)]
    cw, chh, gap, x0, y0 = 250, 170, 30, 120, 220
    for i, (n, label, col) in enumerate(cards):
        x = x0 + i * (cw + gap)
        d.rounded_rectangle([x, y0, x + cw, y0 + chh], radius=14, fill=(16, 16, 24), outline=BORDER, width=2)
        d.text((x + cw//2, y0 + 62), n, font=f(64, bold=True), fill=col, anchor="mm")
        d.text((x + cw//2, y0 + 125), label, font=f(24), fill=DIM, anchor="mm")
    d.text((120, 470), "task-auth-001 — improve authentication · every verdict sealed in lucidota-receipt/1, hash-chained",
           font=f(26), fill=DIM)
    d.text((120, H-110), "real data from /tmp/wreck-demo/dashboard.html — generated by the run you just watched",
           font=f(24), fill=DIM)
    img.save(f"{OUT}/{name}.png")
    return name

